import fs from 'node:fs';
import assert from 'node:assert/strict';
import { parseCSV } from '../js/data.js';
import { buildTableData, csvText, filterRecordRows } from '../js/tables.js';
import { comparisonGroups } from '../js/charts-processing.js';
import { point3Population, properties, rankPairs, correlationColor, propertyNames } from '../js/charts-point3.js';
import { correlation, partialPearson } from '../js/stats.js';
import { formatEquation } from '../js/charts-point2.js';
import { inferenceRows } from '../js/inference.js';

const raw = parseCSV(fs.readFileSync(new URL('../data/steels.csv',import.meta.url),'utf8'));
const headers = raw.shift();
const numeric = new Set([...properties,'C (%)','P (Max)','S(Max)','Mn Avg (%)','Temperature (K)']);
const records = raw.map(row => Object.fromEntries(headers.map((h,i)=>[h,row[i]===''?null:numeric.has(h)?Number(row[i]):row[i]])));
const indexed = records.map((record,i)=>({record,raw:raw[i]}));
assert.equal(records.length,190);
assert.equal(filterRecordRows(indexed,{query:'1006',series:'all',processing:'all'}).length,2);
assert.equal(filterRecordRows(indexed,{series:'main:1',processing:'all'}).length,140);
assert.equal(filterRecordRows(indexed,{series:'family:10',processing:'Hot rolled'}).length,41);
assert.equal(filterRecordRows(indexed,{query:'no existe',series:'all',processing:'all'}).length,0);
assert.deepEqual(parseCSV(csvText(headers,raw)),[headers,...raw]);
assert.deepEqual(parseCSV(csvText(['texto'],[['acero, "azul"'],['línea\nnueva']])),[['texto'],['acero, "azul"'],['línea\nnueva']]);
const tables=buildTableData(records);
assert.equal(tables.descriptive.length,24);assert.equal(tables.correlations.length,40);assert.equal(tables.partial.length,10);
assert.equal(tables.descriptive[0][4],comparisonGroups(records,'1xxx',properties[0]).groups[0].stats.mean);
const pop=point3Population(records);assert.equal(pop.length,138);
assert.ok(Math.abs(correlation(pop,properties[0],properties[2],'spearman').value-.9914)<.0001);
assert.ok(Math.abs(partialPearson(pop,properties,properties[0],properties[2]).partial-.9751)<.0001);
const ranking=rankPairs(pop,'spearman');assert.ok(ranking.every((v,i)=>!i||Math.abs(ranking[i-1].value)>=Math.abs(v.value)));
assert.notEqual(correlationColor(-1),correlationColor(1));assert.notEqual(correlationColor(0),correlationColor(1));
assert.equal(formatEquation(191.742,-76.369),'y = 191.74x − 76.37');
assert.equal(propertyNames['Hardness (HB)'],'Dureza Brinell (HB)');
const inf=JSON.parse(fs.readFileSync(new URL('../data/statistical-results.json',import.meta.url),'utf8'));
assert.equal(inf.anova.length,8);assert.equal(inf.games_howell.length,15);assert.equal(inf.tukey.length,9);assert.equal(inferenceRows(inf).length,32);
assert.ok(Math.abs(inf.anova.find(r=>r.mode==='1xxx'&&r.Property==='UTS (MPa)')['Welch F']-32.69)<.01);
console.log('Website data checks passed.');
